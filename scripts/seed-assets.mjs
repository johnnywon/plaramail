// Writes the Alex profile's photos and logos into TypeScript modules, so the
// Worker carries their bytes without a binary loader. Run after changing a file
// in workers/lib/dev-seed/alex/assets or alex/brands:
//   node scripts/seed-assets.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = "workers/lib/dev-seed/alex";
const header = (what) => `// Copyright (c) 2026 Cloudflare, Inc.\n// Licensed under the Apache 2.0 license found in the LICENSE file or at:\n//     https://opensource.org/licenses/Apache-2.0\n\n// Generated by scripts/seed-assets.mjs from ${what}. Do not edit.\n\n`;

const photos = JSON.parse(readFileSync(`${dir}/assets/manifest.json`, "utf8"));
writeFileSync(`${dir}/photos.ts`, `${header("./assets (see assets/manifest.json for sources and licenses)")}export const PHOTO_BASE64 = {
${photos.map((a) => `\t"${a.assetId}": "${readFileSync(`${dir}/assets/${a.filename}`).toString("base64")}",`).join("\n")}
} as const;
`);

const logos = [];
for (const kind of ["vendor", "original"]) {
	for (const file of readdirSync(`${dir}/brands/${kind}`).filter((f) => /\.(svg|png)$/.test(f)).sort()) {
		const type = file.endsWith(".png") ? "image/png" : "image/svg+xml";
		logos.push(`\t"${file.replace(/\.(svg|png)$/, "")}": "data:${type};base64,${readFileSync(`${dir}/brands/${kind}/${file}`).toString("base64")}",`);
	}
}
writeFileSync(`${dir}/brands/logos.ts`, `${header("./vendor and ./original (see brands/manifest.json)")}export const LOGOS = {
${logos.join("\n")}
} as const;
`);
console.log(`wrote photos.ts (${photos.length}) and brands/logos.ts (${logos.length})`);
